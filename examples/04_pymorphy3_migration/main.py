"""04. Миграция с pymorphy2/pymorphy3 на rulemma: разбор типовых ошибок в поиске и e-commerce."""
from __future__ import annotations

from rulemma import RuLemma

# Реальные ошибки pymorphy3 (2.0.6) на коротких запросах без контекста и корректный результат rulemma
PROBLEMATIC_CASES = [
    ("спрей", "спреть", "спрей"),
    ("кофемашина", "кофемашин", "кофемашина"),
    ("математика", "математик", "математика"),
    ("худи", "худить", "худи"),
    ("сяоми", "сяомь", "сяоми"),
    ("хуавей", "хуавеять", "хуавей"),
    ("плейстейшен", "плейстейсить", "плейстейшен"),
    ("авент", "авента", "авент"),
    ("см", "смотреть", "см"),
    ("е", "быть", "е"),
    ("д", "далее", "д"),
    ("т", "так", "т"),
    ("большие", "больший", "большой"),
    ("воробьев", "воробьёв", "воробей"),
    ("оцинкованные", "оцинковать", "оцинкованный"),
    ("встраиваемые", "встраивать", "встраиваемый"),
    ("развивающие", "развивать", "развивающий"),
    ("отпариватели", "отпариватели (v0.2.0)", "отпариватель"),
]


def main() -> None:
    with RuLemma() as lem:
        print(f"{'Слово':18s} | {'Ошибка pymorphy3':22s} | {'rulemma v0.2.2':18s}")
        print("-" * 66)
        for word, pymorphy_bug, want in PROBLEMATIC_CASES:
            got = lem.word(word)
            assert got == want, f"{word}: got {got!r}, want {want!r}"
            print(f"{word:18s} | {pymorphy_bug:22s} | {got:18s}")


if __name__ == "__main__":
    main()
